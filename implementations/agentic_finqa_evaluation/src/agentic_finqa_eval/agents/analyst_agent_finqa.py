ANALYST_PROMPT_PATH = Path(__file__).parent / "prompts" / "analyst_finqa.txt"
ANALYST_REQUIRED_KEYS = ["answer", "explanation"]

def _load_template() -> str:
    """
    Retrieve the prompt template string from the analyst configuration file.

    Returns
    -------
    str
        The raw text of the analyst prompt template.
    """
    return ANALYST_PROMPT_PATH.read_text()


def build_analyst_task_description(sample: dict, plan: dict) -> str:
    """
    Compose the complete task instruction for the analyst agent.

    Integrates the sample details, the inspection plan, and optional OCR
    data into a single prompt for the model.

    Parameters
    ----------
    sample : dict
        The data sample containing the pre-text, table, post-text and question.
    plan : dict
        The inspection plan generated by the PlannerAgent.
 
    Returns
    -------
    str
        The rendered prompt ready for the vision-capable agent.
    """
    template = _load_template()
    steps = plan.get("steps", [])
    plan_steps_block = "\n".join(f"{i + 1}. {s}" for i, s in enumerate(steps))
    return template.format(
        question=sample['question'],
        pre_text=sample['pre_text'],
        table=sample['table'],
        post_text=sample['post_text'],
        plan_steps_block=plan_steps_block,
    )

def _build_llm(backend: str, model: str, api_key: Optional[str]) -> LLM:
    """
    Configure a CrewAI LLM instance based on the chosen provider.

    Parameters
    ----------
    backend : {'openai', 'gemini'}
        The model provider.
    model : str
        The specific model identifier (e.g., 'gpt-4o').
    api_key : str, optional
        The API key to use. Defaults to provider-specific env variables.

    Returns
    -------
    LLM
        The initialized model interface.

    Raises
    ------
    ValueError
        If an unsupported `backend` is specified.
    """
    if backend == "openai":
        return LLM(
            model=model,
            api_key=api_key or os.environ.get("OPENAI_API_KEY", ""),
            temperature=0,
        )
    if backend == "gemini":
        return LLM(
            model=f"gemini/{model}",
            api_key=api_key or os.environ.get("GEMINI_API_KEY", ""),
            temperature=0,
        )
    raise ValueError(f"Unknown vision agent backend: {backend!r}")


class AnalystAgent:
    """
    An agent that performs analytical reasoning to answer table questions based on a provided plan.
    """
    def __init__(
        self,
        agent_backend: str = "gemini",
        agent_model: str = "gemini-2.5-flash-lite",
        agent_api_key: Optional[str] = None):
        """
        Set up the analyst agent with backends.

        Parameters
        ----------
        agent_backend : str, default 'gemini'
            The backend for the orchestration logic.
        agent_model : str, default 'gemini-2.5-flash-lite'
            The model used for reasoning.
        agent_api_key : str, optional
            API key for the orchestrator.
        """
        self.agent_backend = agent_backend
        self.agent_model = agent_model
        self.agent_api_key = agent_api_key

    def run(
        self,
        sample: dict,
        plan: dict,
        lf_trace: Any = None,
    ) -> Tuple[str, dict, bool, str, List[dict]]:
        """
        Execute the vision analysis process for a single chart question.

        Coordinates the CrewAI agent to follow the plan, call the vision tool,
        and return a structured response.

        Parameters
        ----------
        sample : PerceivedSample
            The question and image to analyze.
        plan : dict
            The inspection procedure to follow.
        langfuse_trace : Any, optional
            Trace object for execution tracking.
        ocr_result : dict, optional
            Ground-truth OCR data for grounding.

        Returns
        -------
        task_description : str
            The prompt used for the task.
        parsed : dict
            The extracted 'answer' and 'explanation'.
        parse_error : bool
            True if the model output was not valid JSON.
        raw_text : str
            The full string returned by the model.
        tool_traces : list of dict
            A log of tool interactions during the run.
        """
        tool = MathOpsTool(
            lf_trace=lf_trace,
        )
        llm = _build_llm(self.agent_backend, self.agent_model, self.agent_api_key)
        task_description = build_analyst_task_description(sample, plan)
        analyst_span = open_llm_span(
            lf_trace,
            name="analyst_agent",
            input_data={"task_description": task_description},
            model=self.agent_model,
            metadata={"backend": self.agent_backend},
        )

        # vision_span = open_llm_span(
        #     lf_trace,
        #     name="vision_agent",
        #     input_data={"task_description": task_description},
        #     model=self.agent_model,
        #     metadata={"backend": self.agent_backend},
        # )
        agent = Agent(
            role="Financial Analyst Agent",
            goal=(
                "Answer questions from financial data that includes pre-text, a table, post-text and a question on that data"
                "then output strict JSON with 'answer' and 'explanation'. Use math_ops_tool whenever calculation is needed."
            ),
            backstory=(
                "You are a financial analysis agent. You carefully review financial data that includes pre-text, a table, post-text and a question on that data"
                "to produce grounded, evidence-based answer to the question."
                "You follow inspection plans provided to you step by step and never hallucinate."
            ),
            llm=llm,
            tools=[tool],
            verbose=False,
            allow_delegation=False,
            max_iter=3,  # limit iterations to prevent runaway tool calls
        )

        task = Task(
            description=task_description,
            expected_output='JSON object: {"answer": "...", "explanation": "..."}',
            agent=agent,
        )

        crew = Crew(agents=[agent], tasks=[task], verbose=False)
        result = crew.kickoff()

        raw_text: str = getattr(result, "raw", None) or str(result)
        parsed, parse_ok = parse_strict(raw_text, required_keys=ANALYST_REQUIRED_KEYS)

        tool_traces = tool.pop_traces()

        close_span(analyst_span, output=parsed if parsed else {"parse_error": True})

        return task_description, parsed, not parse_ok, raw_text, tool_traces